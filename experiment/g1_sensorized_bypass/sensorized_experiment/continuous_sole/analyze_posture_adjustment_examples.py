"""Build small counterfactual examples for foot-attitude adjustment.

The walking controller is not changed.  A timestamped contact snapshot is
held fixed and two hypotheses are compared at the same landing point:

* macro-only: keep the nominal foot attitude because the ankle wrench and the
  full sole support rectangle look acceptable;
* plantar + ankle IMU: use the active-cell support interval and the angular
  velocity to request a small pitch/roll correction.

The correction is represented by the horizontal shift of the load line caused
by a small foot attitude change, ``delta = h*tan(angle)``.  It is a reduced
order counterfactual, not a claim that a closed-loop MuJoCo controller has
already executed the correction.  A snapshot is labelled stable when the
minimum of the four directional margins is at least ``STABILITY_MARGIN_N``.
"""

from __future__ import annotations

